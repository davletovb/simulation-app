import { Button } from '@base-ui/react/button'
import { Dialog } from '@base-ui/react/dialog'
import type { ReactNode } from 'react'

/** Accessible, focus-preserving local command. Styling is scoped to the
 * existing theme tokens; no external CSS/theme service is fetched. */
export function ActionButton({
  children, onClick, disabled = false, tone = 'normal',
}: {
  children: ReactNode
  onClick: () => void
  disabled?: boolean
  tone?: 'normal' | 'primary'
}) {
  return <Button type="button" disabled={disabled}
    focusableWhenDisabled={disabled}
    className={tone === 'primary' ? 'p6-control p6-control-primary' : 'p6-control'}
    onClick={onClick}>{children}</Button>
}

/** Keyboard-accessible, focus-trapped explanation of the *authored* rules. */
export function AssumptionsDialog({ casePack, scope, attribution, cutoff }: {
  casePack: string; scope: string; attribution: string; cutoff: string
}) {
  return <Dialog.Root>
    <Dialog.Trigger className="p6-control">Review assumptions and sources</Dialog.Trigger>
    <Dialog.Portal>
      <Dialog.Backdrop className="p6-dialog-backdrop" />
      <Dialog.Popup className="p6-dialog-popup">
        <Dialog.Title className="p6-dialog-title">What this simulation assumes</Dialog.Title>
        <Dialog.Description>
          The cabinet and society are generated by documented, synthetic rules.
          They are neither a forecast of English policy outcomes nor live public opinion.
        </Dialog.Description>
        <dl className="p6-assumptions">
          <div><dt>Case pack</dt><dd>{casePack}</dd></div>
          <div><dt>Source cutoff (UTC)</dt><dd>{cutoff}</dd></div>
          <div><dt>Evidence classification</dt><dd>{attribution}</dd></div>
          <div><dt>Limits</dt><dd>{scope}</dd></div>
        </dl>
        <Dialog.Close className="p6-control p6-control-primary">Close assumptions</Dialog.Close>
      </Dialog.Popup>
    </Dialog.Portal>
  </Dialog.Root>
}
