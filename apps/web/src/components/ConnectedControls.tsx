import { Button } from '@base-ui/react/button'
import { Dialog } from '@base-ui/react/dialog'
import type { ReactNode } from 'react'
import { Icon } from './Icon'

/** Accessible, focus-preserving local command. It wears the same `.btn`
 * classes as every other button; no external CSS/theme service is fetched. */
export function ActionButton({
  children, onClick, disabled = false, tone = 'normal', size = 'md', describedBy,
}: {
  children: ReactNode
  onClick: () => void
  disabled?: boolean
  tone?: 'normal' | 'primary'
  size?: 'md' | 'sm'
  describedBy?: string
}) {
  const className = `btn ${tone === 'primary' ? 'btn-primary' : 'btn-ghost'}${size === 'sm' ? ' btn-sm' : ''}`
  return <Button type="button" disabled={disabled}
    focusableWhenDisabled={disabled}
    className={className} aria-describedby={describedBy}
    onClick={onClick}>{children}</Button>
}

